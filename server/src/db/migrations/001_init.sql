-- ---------------------------------------------------------------------------
-- Venues: the campus navigation graph nodes. Seeded from
-- src/navigation/venues.js so every event venue maps to a real graph node.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS venues (
  id   text PRIMARY KEY,
  name text NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------------
-- Events: the core entity read by GET /events, AI search and navigation.
-- `date` is a DATE and stays a 'YYYY-MM-DD' string in JSON responses.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS events (
  id           text PRIMARY KEY,
  title        text        NOT NULL,
  category     text        NOT NULL,
  venue_id     text        NOT NULL REFERENCES venues (id) ON UPDATE CASCADE,
  date         date        NOT NULL,
  time         text        NOT NULL,
  duration_min integer     NOT NULL DEFAULT 60 CHECK (duration_min > 0),
  capacity     integer     NOT NULL CHECK (capacity >= 0),
  registered   integer     NOT NULL DEFAULT 0 CHECK (registered >= 0 AND registered <= capacity),
  host         text        NOT NULL DEFAULT '',
  description  text        NOT NULL DEFAULT '',
  tags         jsonb       NOT NULL DEFAULT '[]'::jsonb,
  icon         text        NOT NULL DEFAULT '🎫',
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_events_date     ON events (date);
CREATE INDEX IF NOT EXISTS idx_events_category ON events (category);
CREATE INDEX IF NOT EXISTS idx_events_venue    ON events (venue_id);

-- ---------------------------------------------------------------------------
-- Users. `interests` is a jsonb array of free-form tags
-- (e.g. ["tech","ai","android"]) used for AI search re-ranking and
-- recommendations. A separate interests table would only add joins here.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id            text        PRIMARY KEY,
  name          text        NOT NULL,
  email         text        NOT NULL UNIQUE,
  password_hash text        NOT NULL,
  interests     jsonb       NOT NULL DEFAULT '[]'::jsonb,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Bookmarks: events a user saved. Primary key blocks duplicates by design and
-- is the personalization signal behind /ai/recommendations.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bookmarks (
  user_id    text        NOT NULL REFERENCES users (id)  ON DELETE CASCADE,
  event_id   text        NOT NULL REFERENCES events (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, event_id)
);

CREATE INDEX IF NOT EXISTS idx_bookmarks_user  ON bookmarks (user_id);
CREATE INDEX IF NOT EXISTS idx_bookmarks_event ON bookmarks (event_id);

-- ---------------------------------------------------------------------------
-- Search history: feeds "Similar to your recent searches" personalization.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS search_history (
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  query   text        NOT NULL,
  at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_search_history_user ON search_history (user_id, at DESC);

-- ---------------------------------------------------------------------------
-- Announcements: the BitChat message log, persisted so the REST fallback
-- (GET /chat/announcements) survives a restart.
--
-- The UNIQUE constraint is the duplicate guard: a (room, message) pair can only
-- ever exist once, so the relay can never insert the same announcement twice.
-- `room` stores a bare venue id ("main-hall"); the socket.io room name
-- `announce:<venueId>` is derived at emit time and never persisted.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS announcements (
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room    text        NOT NULL,
  message text        NOT NULL,
  at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT announcements_room_message_key UNIQUE (room, message)
);

CREATE INDEX IF NOT EXISTS idx_announcements_room ON announcements (room, id DESC);