-- ---------------------------------------------------------------------------
-- 009_support_desk.sql  (additive, contract 1.6.0)
--   support_tickets  : one help chat per (user, event); managed by the event's
--                      creator or an admin.
--   support_messages : the thread. sender_role 'user' | 'manager'.
--                      (sender_id, client_id) is the resend idempotency key.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS support_tickets (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id        text        NOT NULL REFERENCES events (id) ON UPDATE CASCADE ON DELETE CASCADE,
  user_id         text        NOT NULL REFERENCES users (id)  ON UPDATE CASCADE ON DELETE CASCADE,
  subject         text        NOT NULL CHECK (char_length(subject) BETWEEN 1 AND 120),
  status          text        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  last_message_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_support_tickets_event ON support_tickets (event_id, last_message_at DESC);
CREATE INDEX IF NOT EXISTS idx_support_tickets_user  ON support_tickets (user_id, last_message_at DESC);

CREATE TABLE IF NOT EXISTS support_messages (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id   bigint      NOT NULL REFERENCES support_tickets (id) ON DELETE CASCADE,
  sender_id   text        REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
  sender_role text        NOT NULL CHECK (sender_role IN ('user', 'manager')),
  body        text        NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
  client_id   text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_support_messages_ticket ON support_messages (ticket_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_support_messages_sender_client
  ON support_messages (sender_id, client_id) WHERE client_id IS NOT NULL;
