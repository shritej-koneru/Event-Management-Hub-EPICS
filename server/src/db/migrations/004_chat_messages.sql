-- ---------------------------------------------------------------------------
-- 004_chat_messages.sql
--
-- Interactive BitChat messages were live-only (broadcast in memory, never
-- stored), so history vanished whenever a client reconnected or restarted.
-- This table is the durable thread behind:
--   - Socket.IO event `chat:message` (write + broadcast)
--   - GET /api/chat/messages (history / reconnect resync)
--
-- Conventions match announcements:
--   - `room` stores a BARE venue id ("main-hall") or NULL for the global
--     namespace-wide thread the Android client joins by default.
--   - No JWT, password, or other secret is ever stored on a message row.
--   - `user_id` is the users.id text key; NULL for Guest / assistant rows.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS chat_messages (
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author  text        NOT NULL,
  user_id text        REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
  room    text        REFERENCES venues (id) ON UPDATE CASCADE ON DELETE SET NULL,
  text    text        NOT NULL,
  bot     boolean     NOT NULL DEFAULT false,
  at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chat_messages_text_length CHECK (char_length(text) BETWEEN 1 AND 500)
);

-- History pages read "latest N for a room" or "latest N globally".
CREATE INDEX IF NOT EXISTS idx_chat_messages_room_at ON chat_messages (room, at DESC);
CREATE INDEX IF NOT EXISTS idx_chat_messages_at ON chat_messages (at DESC);
